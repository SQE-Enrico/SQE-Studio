"""Regression for the RC13.1 Windows SQDMetal sqe_em.png failure.

All outputs below are synthetic file fixtures. No native mesh or Palace solution
is claimed or generated by these tests.
"""
import json
from pathlib import Path
import struct
from types import SimpleNamespace
import zlib

import pytest

from sqe_studio.adapters import sqdmetal_palace_adapter as em
from sqe_studio.adapters.base import EngineBlocked
from sqe_studio.interop.laptop_benchmark import resonator_project


def _chunk(name, contents):
    return (struct.pack('>I', len(contents)) + name + contents
            + struct.pack('>I', zlib.crc32(name + contents) & 0xffffffff))


def _png():
    raw_scanline = b'\x00\x01\x02\x03\xff'
    header = struct.pack('>IIBBBBB', 1, 1, 8, 6, 0, 0, 0)
    return (b'\x89PNG\r\n\x1a\n' + _chunk(b'IHDR', header)
            + _chunk(b'IDAT', zlib.compress(raw_scanline)) + _chunk(b'IEND', b''))


def test_bounded_native_preview_png_is_checked_without_decoder(tmp_path):
    path = tmp_path / 'sqe_em.png'
    path.write_bytes(_png())
    em._validate_native_preview_png(path)
    with pytest.raises(EngineBlocked, match='checksum'):
        altered = bytearray(path.read_bytes())
        altered[-5] ^= 1
        path.write_bytes(altered)
        em._validate_native_preview_png(path)
    with pytest.raises(EngineBlocked, match='signature'):
        path.write_bytes(b'not a png')
        em._validate_native_preview_png(path)
    with pytest.raises(EngineBlocked, match='size'):
        path.write_bytes(b'x' * (em.MAX_NATIVE_PREVIEW_BYTES + 1))
        em._validate_native_preview_png(path)


@pytest.mark.parametrize('filename, payload, allowed', [
    ('sqe_em.png', _png(), True),
    ('sqe_em.png', b'pretend png', False),
    ('unreviewed.png', _png(), False),
    ('unreviewed.py', b'print("unsafe")', False),
])
def test_native_deck_inventory_requires_safe_diagnostic_png(tmp_path, monkeypatch, filename, payload, allowed):
    """Production adapter inventory path, with ONLY mesh/deck creation mocked."""
    project = resonator_project(execution='deck_only')
    project['process']['source'] = 'reviewed'
    study = project['studies'][0]
    monkeypatch.setattr(em, '_native_imports', lambda: object())
    old_import = em.importlib.import_module
    monkeypatch.setattr(em.importlib, 'import_module', lambda name: (
        SimpleNamespace(__version__='fixture') if name == 'gmsh' else old_import(name)))
    monkeypatch.setattr(em, '_physical_ids', lambda *args: ({1}, {2}))
    monkeypatch.setattr(em, '_validate_deck', lambda *args: None)

    def fake_native(study, project, em_options, a02, root):
        folder = root / 'sqe_em'
        (folder / 'sqe_em.msh').write_bytes(b'fixture mesh')
        (folder / 'sqe_em.json').write_text(json.dumps({
            'Problem': {'Output': 'outputFiles'}, 'Model': {'Mesh': 'sqe_em.msh'}
        }), encoding='utf-8')
        (folder / filename).write_bytes(payload)
    monkeypatch.setattr(em, '_make_native', fake_native)
    output = tmp_path / 'out'
    if allowed:
        result = em.run(study, project, output)
        assert 'sqe_em/sqe_em.png' in result['native_files']
        sidecar = json.loads((output / 'a03-native-artifacts.json').read_text(encoding='utf-8'))
        entries = {x['name']: x for x in sidecar['artifacts']}
        assert entries['sqe_em/sqe_em.png']['type'] == 'sqdmetal.diagnostic_png'
        assert entries['sqe_em/sqe_em.png']['bytes'] == len(_png())
        assert sidecar['validation_status'] == 'native_files_checked_not_scientifically_qualified'
    else:
        with pytest.raises(EngineBlocked, match='PNG|extension'):
            em.run(study, project, output)
        assert not (output / 'a03-native-artifacts.json').exists()
